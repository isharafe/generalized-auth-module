CREATE TABLE AUTH_IDENTITY_CHANGE_EVENT (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR(50) NOT NULL,
  EXTERNAL_EVENT_ID VARCHAR(255) NOT NULL,
  EVENT_TYPE VARCHAR(50) NOT NULL,
  EXTERNAL_ISSUER VARCHAR(500) NOT NULL,
  EXTERNAL_SUBJECT VARCHAR(500) NOT NULL,
  OCCURRED_AT TIMESTAMP WITH TIME ZONE,
  RECEIVED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  STATUS VARCHAR(30) NOT NULL,
  ATTEMPTS INTEGER NOT NULL DEFAULT 0,
  PROCESSING_STARTED_AT TIMESTAMP WITH TIME ZONE,
  PROCESSED_AT TIMESTAMP WITH TIME ZONE,
  LAST_ERROR VARCHAR(1000),
  VERSION BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT UK_AUTH_IDENTITY_CHANGE_EVENT UNIQUE (SOURCE_SYSTEM, EXTERNAL_EVENT_ID)
);

CREATE INDEX IX_AUTH_IDENTITY_CHANGE_SUBJECT
  ON AUTH_IDENTITY_CHANGE_EVENT(EXTERNAL_ISSUER, EXTERNAL_SUBJECT);
