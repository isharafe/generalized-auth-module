CREATE TABLE AUTH_ROLE (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE VARCHAR(100) NOT NULL UNIQUE,
  NAME VARCHAR(255) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  VERSION BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE AUTH_PERMISSION_GROUP (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE VARCHAR(100) NOT NULL UNIQUE,
  NAME VARCHAR(255) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  VERSION BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE AUTH_PERMISSION (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE VARCHAR(100) NOT NULL UNIQUE,
  NAME VARCHAR(255) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  RESOURCE_TYPE VARCHAR(30) NOT NULL,
  RESOURCE_PATTERN VARCHAR(1000) NOT NULL,
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  VERSION BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT CK_AUTH_PERMISSION_CODE_TYPE CHECK (
    CODE LIKE CONCAT(RESOURCE_TYPE, ':%')
    AND LENGTH(CODE) > LENGTH(RESOURCE_TYPE) + 1
  )
);

CREATE TABLE AUTH_RESOURCE_RULE (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE VARCHAR(100) NOT NULL UNIQUE,
  RESOURCE_TYPE VARCHAR(30) NOT NULL,
  RESOURCE_PATTERN VARCHAR(1000) NOT NULL,
  ACCESS_MODE VARCHAR(30) NOT NULL,
  PRIORITY INTEGER NOT NULL DEFAULT 0,
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  VERSION BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE AUTH_USER (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EXTERNAL_ISSUER VARCHAR(500) NOT NULL,
  EXTERNAL_SUBJECT VARCHAR(500) NOT NULL,
  USERNAME VARCHAR(255),
  EMAIL VARCHAR(500),
  FIRST_NAME VARCHAR(255),
  LAST_NAME VARCHAR(255),
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  EXTERNAL_DIRECTORY_ID VARCHAR(500),
  LAST_IDENTITY_SYNC_AT TIMESTAMP WITH TIME ZONE,
  IDENTITY_SYNC_STATUS VARCHAR(50),
  ENTITLEMENT_VERSION BIGINT NOT NULL DEFAULT 0,
  VERSION BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT UK_AUTH_USER_IDENTITY UNIQUE (EXTERNAL_ISSUER, EXTERNAL_SUBJECT)
);

CREATE TABLE AUTH_PERMISSION_GROUP_PERMISSION (
  PERMISSION_GROUP_ID BIGINT NOT NULL REFERENCES AUTH_PERMISSION_GROUP(ID),
  PERMISSION_ID BIGINT NOT NULL REFERENCES AUTH_PERMISSION(ID),
  PRIMARY KEY (PERMISSION_GROUP_ID, PERMISSION_ID)
);

CREATE TABLE AUTH_ROLE_PERMISSION_GROUP (
  ROLE_ID BIGINT NOT NULL REFERENCES AUTH_ROLE(ID),
  PERMISSION_GROUP_ID BIGINT NOT NULL REFERENCES AUTH_PERMISSION_GROUP(ID),
  PRIMARY KEY (ROLE_ID, PERMISSION_GROUP_ID)
);

CREATE TABLE AUTH_USER_ROLE (
  USER_ID BIGINT NOT NULL REFERENCES AUTH_USER(ID),
  ROLE_ID BIGINT NOT NULL REFERENCES AUTH_ROLE(ID),
  ASSIGNMENT_SOURCE VARCHAR(30) NOT NULL,
  SOURCE_REFERENCE VARCHAR(1000),
  PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE TABLE AUTH_USER_PERMISSION_GROUP (
  USER_ID BIGINT NOT NULL REFERENCES AUTH_USER(ID),
  PERMISSION_GROUP_ID BIGINT NOT NULL REFERENCES AUTH_PERMISSION_GROUP(ID),
  ASSIGNMENT_SOURCE VARCHAR(30) NOT NULL,
  SOURCE_REFERENCE VARCHAR(1000),
  PRIMARY KEY (USER_ID, PERMISSION_GROUP_ID)
);

CREATE TABLE AUTH_EXTERNAL_AUTHORITY_MAPPING (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR(50) NOT NULL,
  AUTHORITY_TYPE VARCHAR(50) NOT NULL,
  AUTHORITY_VALUE VARCHAR(1000) NOT NULL,
  TARGET_TYPE VARCHAR(50) NOT NULL,
  TARGET_CODE VARCHAR(100) NOT NULL,
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  VERSION BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT UK_AUTH_EXTERNAL_MAPPING UNIQUE (
    SOURCE_SYSTEM,
    AUTHORITY_TYPE,
    AUTHORITY_VALUE,
    TARGET_TYPE,
    TARGET_CODE
  )
);

CREATE TABLE AUTH_PENDING_USER_ASSIGNMENT (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EXTERNAL_ISSUER VARCHAR(500) NOT NULL,
  EXTERNAL_SUBJECT VARCHAR(500) NOT NULL,
  TARGET_TYPE VARCHAR(50) NOT NULL,
  TARGET_CODE VARCHAR(100) NOT NULL,
  ASSIGNMENT_SOURCE VARCHAR(30) NOT NULL,
  CONSTRAINT UK_AUTH_PENDING UNIQUE (
    EXTERNAL_ISSUER,
    EXTERNAL_SUBJECT,
    TARGET_TYPE,
    TARGET_CODE,
    ASSIGNMENT_SOURCE
  )
);

CREATE TABLE AUTH_SEED_HISTORY (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOURCE VARCHAR(1000) NOT NULL,
  CHECKSUM VARCHAR(64) NOT NULL,
  STATUS VARCHAR(30) NOT NULL,
  APPLIED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE AUTH_AUDIT_EVENT (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TIMESTAMP TIMESTAMP WITH TIME ZONE NOT NULL,
  EVENT_KIND VARCHAR(30) NOT NULL,
  EVENT_TYPE VARCHAR(100) NOT NULL,
  ACTOR_ISSUER VARCHAR(500),
  ACTOR_SUBJECT VARCHAR(500),
  EVENT_TARGET VARCHAR(1000),
  AUDIT_ACTION VARCHAR(100),
  CORRELATION_ID VARCHAR(255),
  DETAILS_JSON VARCHAR(4000),
  REQUEST_METHOD VARCHAR(20),
  REQUEST_PATH VARCHAR(1000),
  DECISION VARCHAR(30),
  REASON VARCHAR(100),
  RULE_CODE VARCHAR(100),
  PERMISSION_CODE VARCHAR(100)
);

CREATE INDEX IX_AUTH_AUDIT_EVENT_KIND ON AUTH_AUDIT_EVENT(EVENT_KIND);

CREATE TABLE AUTH_SYNC_STATE (
  SYNC_KEY VARCHAR(100) PRIMARY KEY,
  STATUS VARCHAR(50),
  UPDATED_AT TIMESTAMP WITH TIME ZONE,
  DETAILS VARCHAR(1000),
  VERSION BIGINT NOT NULL DEFAULT 0
);

